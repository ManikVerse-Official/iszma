/*
 * Builds ReportCard Studio for embedding inside Ishmaverse.
 *
 * The Studio is a self-contained SPA, so it is shipped as a static sub-app at
 * `/reportcard/` and rendered inside the Ishmaverse section view through an
 * iframe. Building with `VITE_BASE=/reportcard/` makes every asset, the PWA
 * manifest and the service worker scope resolve under that folder, and the
 * output is copied into `public/reportcard` so `npm run build` (and `vite dev`)
 * on Ishmaverse serve it with zero extra wiring.
 *
 * The browser only ever loads `public/reportcard`, so that folder is the active
 * embed. `dist/` here is a staging area that is overwritten on every run and
 * must never be served or hand-edited: a second copy under the repo root
 * (`dist/reportcard`) is Ishmaverse's own output, regenerated by its build.
 *
 *   node scripts/build-embed.mjs        (or: npm run build:embed)
 */
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, readFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const studioRoot = resolve(here, '..');
const distDir = resolve(studioRoot, 'dist');
const targetDir = resolve(studioRoot, '..', 'public', 'reportcard');

console.log('[reportcard] Building with base=/reportcard/ …');

const result = spawnSync('npx', ['vite', 'build'], {
  cwd: studioRoot,
  stdio: 'inherit',
  shell: true,
  env: { ...process.env, VITE_BASE: '/reportcard/' },
});

if (result.status !== 0) {
  console.error('[reportcard] Build failed.');
  process.exit(result.status ?? 1);
}

if (!existsSync(distDir)) {
  console.error('[reportcard] No dist/ output found after build.');
  process.exit(1);
}

rmSync(targetDir, { recursive: true, force: true });
cpSync(distDir, targetDir, { recursive: true });

console.log(`[reportcard] Copied build → ${targetDir}`);

/*
 * Verify the ACTIVE embed shell now points at assets that were just copied.
 *
 * public/reportcard is the only path the browser loads, so a shell left over
 * from an earlier build (or an interrupted copy) would silently keep serving an
 * outdated bundle. Failing here, loudly, is better than debugging a UI that is
 * quietly running last month's code.
 */
const shellPath = resolve(targetDir, 'index.html');
if (!existsSync(shellPath)) {
  console.error(`[reportcard] The copied shell is missing: ${shellPath}`);
  process.exit(1);
}

const shell = readFileSync(shellPath, 'utf8');
const referenced = [...shell.matchAll(/(?:src|href)="(\/reportcard\/assets\/[^"?]+)"/g)].map(
  (match) => match[1],
);

if (referenced.length === 0) {
  console.error('[reportcard] The copied shell references no build assets — refusing to ship it.');
  process.exit(1);
}

/* `/reportcard/assets/x.js` lives at `public/reportcard/assets/x.js`. */
const localPath = (url) => resolve(targetDir, url.replace(/^\/reportcard\//, ''));
const missing = referenced.filter((url) => !existsSync(localPath(url)));
if (missing.length > 0) {
  console.error('[reportcard] The copied shell points at assets that do not exist:');
  for (const url of missing) console.error(`  • ${url}`);
  process.exit(1);
}

console.log(`[reportcard] Active embed shell → ${referenced.join(', ')}`);
